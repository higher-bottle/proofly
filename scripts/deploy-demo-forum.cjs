const hre = require("hardhat");
const fs = require("node:fs");
const path = require("node:path");

async function main() {
  const helpAddress = process.env.DEMO_HELP_ADDRESS;
  const badgeAddress = process.env.DEMO_BADGE_ADDRESS;
  const lifetime = BigInt(process.env.QUESTION_LIFETIME_SECONDS || 180);
  if (!hre.ethers.isAddress(helpAddress) || !hre.ethers.isAddress(badgeAddress)) throw new Error("DEMO_HELP_ADDRESS and DEMO_BADGE_ADDRESS are required");
  const [deployer] = await hre.ethers.getSigners();
  const Forum = await hre.ethers.getContractFactory("ProoflyForumVideoDemo");
  const askerStudentId = hre.ethers.id("proofly-video-demo-asker");
  const deployTx = await Forum.getDeployTransaction(helpAddress, deployer.address, deployer.address, askerStudentId, lifetime);
  const [gas, feeData, balance] = await Promise.all([hre.ethers.provider.estimateGas({...deployTx,from:deployer.address}),hre.ethers.provider.getFeeData(),hre.ethers.provider.getBalance(deployer.address)]);
  const gasPrice = feeData.maxFeePerGas || feeData.gasPrice;
  const estimatedCost = gas * gasPrice;
  console.log("Deployer:", deployer.address);
  console.log("Balance:", hre.ethers.formatEther(balance), "ETH");
  console.log("Estimated gas:", gas.toString());
  console.log("Estimated Forum deployment:", hre.ethers.formatEther(estimatedCost), "ETH");
  if (balance < estimatedCost) throw new Error(`Insufficient Sepolia ETH; need approximately ${hre.ethers.formatEther(estimatedCost - balance)} more ETH`);
  const forum = await Forum.deploy(helpAddress, deployer.address, deployer.address, askerStudentId, lifetime, {gasLimit: gas * 105n / 100n}); await forum.waitForDeployment();
  const help = new hre.ethers.Contract(helpAddress,["function owner() view returns(address)","function transferOwnership(address)"],deployer);
  if ((await help.owner()).toLowerCase() !== deployer.address.toLowerCase()) throw new Error("Recovered HELP is not owned by deployer");
  await (await help.transferOwnership(await forum.getAddress())).wait();
  const network = await hre.ethers.provider.getNetwork();
  const config = `// Generated by the Proofly demo deployment script.\nexport const PROOFLY_CONTRACTS = Object.freeze({\n  chainId: ${network.chainId},\n  helpToken: "${helpAddress}",\n  badge: "${badgeAddress}",\n  forum: "${await forum.getAddress()}"\n});\n`;
  fs.writeFileSync(path.join(__dirname,"..","dist","contracts.js"),config);
  console.log("Demo HELP:", helpAddress);
  console.log("Existing badge:", badgeAddress);
  console.log("Demo Forum:", await forum.getAddress());
  console.log("Question lifetime:", lifetime.toString(), "seconds");
}
main().catch(error=>{console.error(error);process.exitCode=1});
