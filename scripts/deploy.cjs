const hre = require("hardhat");
const fs = require("node:fs");
const path = require("node:path");

async function main() {
  const HelpToken = await hre.ethers.getContractFactory("HelpToken");
  const help = await HelpToken.deploy();
  await help.waitForDeployment();
  const ProoflyBadge = await hre.ethers.getContractFactory("ProoflyBadge");
  const [deployer] = await hre.ethers.getSigners();
  const issuerAddress = process.env.BADGE_ISSUER_ADDRESS || process.env.ADMIN || deployer.address;
  const badge = await ProoflyBadge.deploy(issuerAddress);
  await badge.waitForDeployment();
  const ProoflyForum = await hre.ethers.getContractFactory("ProoflyForum");
  const questionLifetime = BigInt(process.env.QUESTION_LIFETIME_SECONDS || 30 * 24 * 60 * 60);
  const forum = await ProoflyForum.deploy(await help.getAddress(), issuerAddress, questionLifetime);
  await forum.waitForDeployment();
  await (await help.transferOwnership(await forum.getAddress())).wait();
  const helpAddress = await help.getAddress();
  const badgeAddress = await badge.getAddress();
  const forumAddress = await forum.getAddress();
  const network = await hre.ethers.provider.getNetwork();
  const config = `// Generated by the Proofly deployment script. Do not edit manually.\nexport const PROOFLY_CONTRACTS = Object.freeze({\n  chainId: ${network.chainId.toString()},\n  helpToken: "${helpAddress}",\n  badge: "${badgeAddress}",\n  forum: "${forumAddress}"\n});\n`;
  fs.writeFileSync(path.join(__dirname, "..", "dist", "contracts.js"), config);
  console.log("HELP token:   ", helpAddress);
  console.log("Proofly badge:", badgeAddress);
  console.log("Proofly forum:", forumAddress);
  console.log("Question lifetime:", questionLifetime.toString(), "seconds");
  console.log("Updated dist/contracts.js automatically.");
}

main().catch(error => { console.error(error); process.exitCode = 1; });
